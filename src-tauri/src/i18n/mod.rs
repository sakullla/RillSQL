//! zh-CN / en 字典。键与 Vue 文案一致；两边都有的句子保持同一写法。

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Locale {
    #[default]
    ZhCn,
    En,
}

pub fn text(locale: Locale, key: &str) -> String {
    let value = match locale {
        Locale::ZhCn => zh(key),
        Locale::En => en(key),
    };
    value.unwrap_or(key).to_owned()
}

/// 字典里的原文（静态字符串）；没有这个键时为 None。
pub fn static_text(locale: Locale, key: &str) -> Option<&'static str> {
    match locale {
        Locale::ZhCn => zh(key),
        Locale::En => en(key),
    }
}

pub fn fill(template: &str, pairs: &[(&str, &str)]) -> String {
    let mut text = template.to_owned();
    for (key, value) in pairs {
        text = text.replace(&format!("{{{key}}}"), value);
    }
    text
}

macro_rules! dict {
    ($($key:literal => $zh:literal, $en:literal;)*) => {
        fn zh(key: &str) -> Option<&'static str> {
            Some(match key {
                $($key => $zh,)*
                _ => return None,
            })
        }
        fn en(key: &str) -> Option<&'static str> {
            Some(match key {
                $($key => $en,)*
                _ => return None,
            })
        }
        #[allow(dead_code)]
        pub fn catalog_keys() -> &'static [&'static str] {
            &[$($key),*]
        }
    };
}

