#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_locales_translate_every_catalog_key() {
        for key in catalog_keys() {
            for locale in [Locale::ZhCn, Locale::En] {
                let value = text(locale, key);
                assert_ne!(value, *key, "{key:?} {locale:?}");
                assert!(!value.is_empty(), "{key}");
            }
        }
    }
}
