//! SQL Server 的 SQL 语法：标识符引号与保留字。

use crate::adapters::SqlSyntax;

pub(super) struct SqlserverSyntax;

impl SqlSyntax for SqlserverSyntax {
    /// T-SQL 的括号标识符转义是 ]]。
    fn quote_always(&self, name: &str) -> String {
        format!("[{}]", name.replace(']', "]]"))
    }

    fn reserved_words(&self) -> &'static [&'static str] {
        RESERVED
    }
}

