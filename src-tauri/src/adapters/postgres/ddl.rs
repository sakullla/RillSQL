//! PostgreSQL 的 DDL 方言：按模式限定、标识列、就地替换视图、注释语句，以及序列/枚举/域的库级动作。

use crate::adapters::ddl::{AdminSections, Comments, DdlDialect, ViewModifier};
use crate::adapters::quote_ident;
use crate::connections::model::Engine;
use crate::connections::CatalogSession;
use crate::ddl::introspect::SESSION_MISMATCH;
use crate::ddl::model::{Action, Column, ColumnDraft, Plan, Request, Risk, SequenceState, Snapshot, Step};
use crate::ddl::plan::{finish, normalize_default, same_type, statement_alter_plan, target_label, word_is, Change, Tok};
use crate::ddl::sql::{qualified_table, valid_default, valid_name};

use super::ddl_read;

pub(in crate::adapters) struct PostgresDdl;

#[async_trait::async_trait]
impl DdlDialect for PostgresDdl {
    fn qualified_table(&self, _database: &str, schema: &str, table: &str) -> Result<String, String> {
        if schema.is_empty() {
            return Err("PostgreSQL 需要指定 schema（表所在的分组名），没有另开连接。".to_owned());
        }
        Ok(crate::adapters::qualified(Engine::Postgres, &[schema, table]))
    }

    fn target_scope(&self, database: &str, schema: &str, table: &str) -> String {
        format!("{database} / {schema}.{table}")
    }

    fn rule_text(&self) -> &'static str {
        "这些语句逐条执行，失败即停。已经成功的语句不撤销。PostgreSQL 虽然可以把结构变更放进事务，这里也不包成一个大事务，不能据此认为所有数据库都会回滚。"
    }

    fn auto_clause_before_null(&self, draft: &ColumnDraft) -> &'static str {
        if draft.auto && draft.primary {
            " GENERATED ALWAYS AS IDENTITY"
        } else {
            ""
        }
    }

    fn alter_plan(&self, snapshot: &Snapshot, table: &str, _drafts: &[ColumnDraft], changes: &[Change], target: String, risks: Vec<Risk>) -> Plan {
        statement_alter_plan(snapshot, table, changes, target, risks, "ADD COLUMN", &|qualified, original, draft| Ok(modify_column(qualified, original, draft)))
    }

    fn drop_index_sql(&self, snapshot: &Snapshot, index: &str) -> Result<String, String> {
        // 索引名不带 schema 不能定位：索引建在表所在 schema。
        Ok(format!("DROP INDEX {}.{index};", quote_ident(Engine::Postgres, &snapshot.schema)))
    }

    fn references_cross_schema(&self) -> bool {
        true
    }

    /// 目标表总按外键写明的模式读取与限定（没写模式时由限定名报出缺少 schema）。
    fn reference_scope<'a>(&self, ref_schema: &'a str) -> Option<&'a str> {
        Some(ref_schema)
    }

    fn truncate_note(&self) -> &'static str {
        "TRUNCATE TABLE 不触发逐行的 DELETE 触发器，不重置关联序列，也不加 CASCADE。"
    }

    fn drop_view_keyword(&self, materialized: bool) -> &'static str {
        if materialized {
            "DROP MATERIALIZED VIEW"
        } else {
            "DROP VIEW"
        }
    }

    /// CREATE MATERIALIZED VIEW：替换会丢弃物化数据。
    fn view_modifier(&self, tokens: &[Tok], index: usize) -> Option<ViewModifier> {
        tokens.get(index).filter(|token| word_is(token, "materialized")).map(|_| ViewModifier::Materialized(index + 1))
    }

    fn replaces_view_in_place(&self) -> bool {
        true
    }

    fn rebuilt_missing(&self) -> &'static [&'static str] {
        &["存储参数与表空间", "权限", "触发器"]
    }

    fn rebuilt_identity_missing(&self) -> Option<&'static str> {
        Some("标识列的 ALWAYS / BY DEFAULT 模式与序列参数（统一写成 BY DEFAULT）")
    }

    fn generated_column_clause(&self, expression: &str) -> Option<String> {
        Some(format!(" GENERATED ALWAYS AS ({expression}) STORED"))
    }

    fn rebuilt_auto_clause(&self) -> &'static str {
        " GENERATED BY DEFAULT AS IDENTITY"
    }

    fn comment_statements(&self, snapshot: &Snapshot, qualified: &str) -> Vec<String> {
        let literal = |text: &str| text.replace('\'', "''");
        let mut statements = Vec::new();
        if let Some(comment) = &snapshot.table_comment {
            statements.push(format!("COMMENT ON TABLE {qualified} IS '{}';", literal(comment)));
        }
        for column in &snapshot.columns {
            if let Some(comment) = snapshot.column_comments.get(&column.name) {
                statements.push(format!("COMMENT ON COLUMN {qualified}.{} IS '{}';", quote_ident(Engine::Postgres, &column.name), literal(comment)));
            }
        }
        statements
    }

    fn plan_object_action(&self, snapshot: &Snapshot, action: &Action) -> Option<Plan> {
        object_action(snapshot, action, true)
    }

    fn refuse_object_action(&self, snapshot: &Snapshot, action: &Action) -> Option<Plan> {
        object_action(snapshot, action, false)
    }

    fn admin_sections(&self) -> AdminSections {
        AdminSections { extensions: true, sequences: true, enums: true, domains: true, ..AdminSections::default() }
    }

    fn matches_session(&self, session: &CatalogSession) -> bool {
        matches!(session, CatalogSession::Postgres(_))
    }

    async fn load_snapshot(&self, session: &CatalogSession, request: &Request, table: &str) -> Result<Snapshot, String> {
        let CatalogSession::Postgres(client) = session else {
            return Err(SESSION_MISMATCH.to_owned());
        };
        ddl_read::load_postgres(client, &request.database, &request.schema, table).await
    }

    async fn name_taken(&self, session: &CatalogSession, snapshot: &Snapshot, name: &str) -> Result<bool, String> {
        let CatalogSession::Postgres(client) = session else {
            return Err(SESSION_MISMATCH.to_owned());
        };
        ddl_read::name_taken(client, &snapshot.schema, &snapshot.name, name).await
    }

    async fn count(&self, session: &CatalogSession, sql: &str) -> Result<i64, String> {
        let CatalogSession::Postgres(client) = session else {
            return Err(SESSION_MISMATCH.to_owned());
        };
        ddl_read::count(client, sql).await
    }

    async fn load_comments(&self, session: &CatalogSession, schema: &str, table: &str) -> Option<Result<Comments, String>> {
        let CatalogSession::Postgres(client) = session else {
            return None;
        };
        Some(ddl_read::postgres_comments(client, schema, table).await)
    }

    async fn read_object_state(&self, session: &CatalogSession, request: &Request, snapshot: &mut Snapshot) -> Result<(), String> {
        let client = match (&request.action, session) {
            (Action::AlterSequence { .. } | Action::AddEnumValue { .. } | Action::AlterDomain { .. }, CatalogSession::Postgres(client)) => client,
            (Action::AlterSequence { .. } | Action::AddEnumValue { .. } | Action::AlterDomain { .. }, _) => return Err(SESSION_MISMATCH.to_owned()),
            _ => return Ok(()),
        };
        match &request.action {
            Action::AlterSequence { sequence, .. } => snapshot.sequence = Some(ddl_read::postgres_sequence(client, &request.schema, sequence).await?),
            Action::AddEnumValue { enum_name, .. } => snapshot.enum_values = ddl_read::postgres_enum_values(client, &request.schema, enum_name).await?,
            Action::AlterDomain { domain, .. } => snapshot.domain = Some(ddl_read::postgres_domain(client, &request.schema, domain).await?),
            _ => {}
        }
        Ok(())
    }
}

/// 改一个字段：改名、改类型（带 USING 转换）、改可空、改默认值，各一条语句。
fn modify_column(qualified: &str, original: &Column, draft: &ColumnDraft) -> Vec<Step> {
    let engine = Engine::Postgres;
    let mut steps = Vec::new();
    if draft.name.trim() != original.name {
        steps.push(Step {
            sql: format!(
                "ALTER TABLE {qualified} RENAME COLUMN {} TO {};",
                quote_ident(engine, &original.name),
                quote_ident(engine, draft.name.trim())
            ),
            label: format!("重命名 {} → {}", original.name, draft.name.trim()),
        });
    }
    let column_name = quote_ident(engine, draft.name.trim());
    if !same_type(&draft.type_name, &original.type_name) {
        let type_name = draft.type_name.trim();
        steps.push(Step {
            sql: format!("ALTER TABLE {qualified} ALTER COLUMN {column_name} TYPE {type_name} USING {column_name}::{type_name};"),
            label: format!("修改类型 {}", draft.name.trim()),
        });
    }
    if draft.nullable != original.nullable {
        let verb = if draft.nullable { "DROP NOT NULL" } else { "SET NOT NULL" };
        steps.push(Step {
            sql: format!("ALTER TABLE {qualified} ALTER COLUMN {column_name} {verb};"),
            label: if draft.nullable { format!("允许 NULL {}", draft.name.trim()) } else { format!("设置 NOT NULL {}", draft.name.trim()) },
        });
    }
    if normalize_default(&draft.default_sql) != original.default_sql.as_deref().map(str::trim) {
        let sql = if draft.default_sql.trim().is_empty() {
            format!("ALTER TABLE {qualified} ALTER COLUMN {column_name} DROP DEFAULT;")
        } else {
            format!("ALTER TABLE {qualified} ALTER COLUMN {column_name} SET DEFAULT {};", draft.default_sql.trim())
        };
        steps.push(Step { sql, label: format!("修改默认值 {}", draft.name.trim()) });
    }
    steps
}

/// PostgreSQL 的库级动作。`supported` 为假时是别的引擎请求了它：给出同一个动作的拒绝计划。
fn object_action(snapshot: &Snapshot, action: &Action, supported: bool) -> Option<Plan> {
    Some(match action {
        Action::AlterSequence { sequence, start, increment, min_value, max_value, cycle } => plan_alter_sequence(
            snapshot,
            sequence,
            &SequenceState { start: *start, increment: *increment, min_value: *min_value, max_value: *max_value, cycle: *cycle },
            supported,
        ),
        Action::AddEnumValue { enum_name, value, before } => plan_add_enum_value(snapshot, enum_name, value, before.as_deref(), supported),
        Action::AlterDomain { domain, default_sql, not_null } => plan_alter_domain(snapshot, domain, default_sql.as_deref(), *not_null, supported),
        _ => return None,
    })
}

fn plan_alter_sequence(snapshot: &Snapshot, sequence: &str, wanted: &SequenceState, supported: bool) -> Plan {
    let target = target_label(snapshot.engine, &snapshot.database, &snapshot.schema, sequence);
    let mut risks = vec![Risk {
        level: "info".to_owned(),
        text: "序列参数改完立即生效，之后取号按新参数生成。已有数据里的号不会因此改变。".to_owned(),
    }];
    if !supported {
        return finish(
            snapshot.engine,
            false,
            target,
            vec!["只有 PostgreSQL 的序列参数由这里修改；其它引擎请在查询里自己写 ALTER SEQUENCE。".to_owned()],
            risks,
            Vec::new(),
        );
    }
    let mut blocked = Vec::new();
    if !valid_name(sequence) {
        blocked.push("序列名无效。".to_owned());
    }
    let Some(current) = snapshot.sequence.as_ref() else {
        blocked.push(format!("没有读到序列 {sequence} 的参数，没有生成语句。"));
        return finish(snapshot.engine, false, target, blocked, risks, Vec::new());
    };
    if current.start.is_none() && current.increment.is_none() && current.min_value.is_none() && current.max_value.is_none() && current.cycle.is_none() {
        blocked.push(format!("序列 {sequence} 的参数读不到（可能是权限不足），没有生成语句。"));
    }
    if wanted.increment == Some(0) {
        blocked.push("步长不能是 0。".to_owned());
    }
    if let (Some(min), Some(max)) = (wanted.min_value.or(current.min_value), wanted.max_value.or(current.max_value)) {
        if min >= max {
            blocked.push("最小值必须小于最大值。".to_owned());
        }
    }
    let mut clauses: Vec<String> = Vec::new();
    if let Some(value) = wanted.increment {
        if current.increment != Some(value) {
            clauses.push(format!("INCREMENT BY {value}"));
        }
    }
    if let Some(value) = wanted.min_value {
        if current.min_value != Some(value) {
            clauses.push(format!("MINVALUE {value}"));
        }
    }
    if let Some(value) = wanted.max_value {
        if current.max_value != Some(value) {
            clauses.push(format!("MAXVALUE {value}"));
        }
    }
    if let Some(value) = wanted.start {
        if current.start != Some(value) {
            clauses.push(format!("START WITH {value}"));
        }
    }
    if let Some(cycle) = wanted.cycle {
        if current.cycle != Some(cycle) {
            clauses.push(if cycle { "CYCLE".to_owned() } else { "NO CYCLE".to_owned() });
        }
    }
    if clauses.iter().any(|clause| clause.starts_with("START WITH")) {
        risks.push(Risk {
            level: "warn".to_owned(),
            text: "START WITH 只改以后 RESTART 用的起点，不会移动已经取到的号；要移动当前号得另外 RESTART。".to_owned(),
        });
    }
    if clauses.iter().any(|clause| clause.starts_with("MAXVALUE") || clause.starts_with("MINVALUE")) {
        risks.push(Risk {
            level: "warn".to_owned(),
            text: "调小上界或调大下界可能让之后的取号失败；这里不检查已经用掉的号。".to_owned(),
        });
    }
    if !blocked.is_empty() {
        return finish(snapshot.engine, false, target, blocked, risks, Vec::new());
    }
    if clauses.is_empty() {
        return finish(snapshot.engine, false, target, vec![format!("序列 {sequence} 的参数没有变化。")], risks, Vec::new());
    }
    match qualified_table(snapshot.engine, &snapshot.database, &snapshot.schema, sequence) {
        Ok(name) => {
            let sql = format!("ALTER SEQUENCE {name} {};", clauses.join(" "));
            finish(snapshot.engine, false, target, Vec::new(), risks, vec![Step { label: format!("修改序列 {sequence}"), sql }])
        }
        Err(message) => finish(snapshot.engine, false, target, vec![message], risks, Vec::new()),
    }
}

fn plan_add_enum_value(snapshot: &Snapshot, enum_name: &str, value: &str, before: Option<&str>, supported: bool) -> Plan {
    let target = target_label(snapshot.engine, &snapshot.database, &snapshot.schema, enum_name);
    let mut risks = vec![Risk {
        level: "info".to_owned(),
        text: "枚举值只能追加，不能删除或调整顺序；已有的行不会被改写。".to_owned(),
    }];
    if !supported {
        return finish(snapshot.engine, false, target, vec!["只有 PostgreSQL 有枚举类型，这里不生成语句。".to_owned()], risks, Vec::new());
    }
    let trimmed = value.trim();
    let mut blocked = Vec::new();
    if !valid_name(enum_name) {
        blocked.push("枚举名无效。".to_owned());
    }
    if trimmed.is_empty() {
        blocked.push("枚举值不能为空。".to_owned());
    } else if trimmed.chars().any(char::is_control) {
        blocked.push("枚举值里不能有控制字符。".to_owned());
    } else if trimmed.len() > 63 {
        blocked.push("PostgreSQL 的枚举值最长 63 字节。".to_owned());
    }
    if snapshot.enum_values.is_empty() {
        blocked.push(format!("没有读到枚举 {enum_name} 的现有取值（可能不是枚举或权限不足），没有生成语句。"));
    } else if snapshot.enum_values.iter().any(|item| item == trimmed) {
        blocked.push(format!("{trimmed} 已经是 {enum_name} 的值，没有生成语句。"));
    }
    let before = before.map(str::trim).filter(|item| !item.is_empty());
    if let Some(at) = before {
        if !snapshot.enum_values.iter().any(|item| item == at) {
            blocked.push(format!("找不到枚举值 {at}，没有生成语句。"));
        }
        if at == trimmed {
            blocked.push("不能把新值放在它自己前面。".to_owned());
        }
    }
    if !blocked.is_empty() {
        return finish(snapshot.engine, false, target, blocked, risks, Vec::new());
    }
    risks.push(Risk {
        level: "warn".to_owned(),
        text: "新值要在这条语句执行完之后才能被使用；这里单条执行，不把追加值和使用它的语句放进同一个事务。".to_owned(),
    });
    let literal = format!("'{}'", trimmed.replace('\'', "''"));
    let placement = match before {
        Some(at) => format!(" BEFORE '{}'", at.replace('\'', "''")),
        None => String::new(),
    };
    match qualified_table(snapshot.engine, &snapshot.database, &snapshot.schema, enum_name) {
        Ok(name) => {
            let sql = format!("ALTER TYPE {name} ADD VALUE {literal}{placement};");
            finish(snapshot.engine, false, target, Vec::new(), risks, vec![Step { label: format!("给 {enum_name} 追加值 {trimmed}"), sql }])
        }
        Err(message) => finish(snapshot.engine, false, target, vec![message], risks, Vec::new()),
    }
}

fn plan_alter_domain(snapshot: &Snapshot, domain: &str, default_sql: Option<&str>, not_null: Option<bool>, supported: bool) -> Plan {
    let target = target_label(snapshot.engine, &snapshot.database, &snapshot.schema, domain);
    let mut risks = vec![Risk {
        level: "info".to_owned(),
        text: "域的默认值只影响之后插入的行，不改已有数据。".to_owned(),
    }];
    if !supported {
        return finish(snapshot.engine, false, target, vec!["只有 PostgreSQL 有域（domain）对象，这里不生成语句。".to_owned()], risks, Vec::new());
    }
    let mut blocked = Vec::new();
    if !valid_name(domain) {
        blocked.push("域名无效。".to_owned());
    }
    let Some(current) = snapshot.domain.as_ref() else {
        blocked.push(format!("没有读到域 {domain} 的定义，没有生成语句。"));
        return finish(snapshot.engine, false, target, blocked, risks, Vec::new());
    };
    let mut changes: Vec<(String, String)> = Vec::new();
    if let Some(raw) = default_sql {
        let text = raw.trim();
        if text.is_empty() || text.eq_ignore_ascii_case("null") {
            if current.default_sql.is_some() {
                changes.push(("删除域默认值".to_owned(), "DROP DEFAULT".to_owned()));
            }
        } else if !valid_default(Engine::Postgres, text) {
            blocked.push("默认值只接受字面量、TRUE/FALSE、now() 或 CURRENT_TIMESTAMP。".to_owned());
        } else if current.default_sql.as_deref() != Some(text) {
            changes.push(("修改域默认值".to_owned(), format!("SET DEFAULT {text}")));
        }
    }
    if let Some(not_null) = not_null {
        if current.not_null != not_null {
            changes.push(("修改域 NOT NULL".to_owned(), if not_null { "SET NOT NULL".to_owned() } else { "DROP NOT NULL".to_owned() }));
            if not_null {
                risks.push(Risk {
                    level: "warn".to_owned(),
                    text: "SET NOT NULL 会先检查已有数据，存在空值时数据库会报错；这里不先改写数据。".to_owned(),
                });
            }
        }
    }
    if !blocked.is_empty() {
        return finish(snapshot.engine, false, target, blocked, risks, Vec::new());
    }
    if changes.is_empty() {
        return finish(snapshot.engine, false, target, vec![format!("域 {domain} 的默认值与 NOT NULL 没有变化。")], risks, Vec::new());
    }
    match qualified_table(snapshot.engine, &snapshot.database, &snapshot.schema, domain) {
        Ok(name) => {
            let steps = changes
                .into_iter()
                .map(|(label, clause)| Step { sql: format!("ALTER DOMAIN {name} {clause};"), label })
                .collect::<Vec<_>>();
            finish(snapshot.engine, false, target, Vec::new(), risks, steps)
        }
        Err(message) => finish(snapshot.engine, false, target, vec![message], risks, Vec::new()),
    }
}

